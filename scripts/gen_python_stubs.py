"""Generate `bindings/python/python/wickra/__init__.pyi` from the binding source.

The stub file was hand-written and had stopped tracking the extension: it
described 72 of the 520 exported names, and it described them in terms of
`numpy.typing.NDArray`, which the binding stopped returning when the NumPy
dependency was dropped. Both are the kind of drift that only a generator fixes
for good, so the signatures are read out of `bindings/python/src/lib.rs`.

Two shapes have to be read, because that is how the binding is written:

* a class spelled out directly, as `#[pyclass(name = "SMA")] struct PySma` plus
  a `#[pymethods] impl PySma` block;
* a class produced by one of the nine `macro_rules!` wrappers, where the method
  signatures live once in the macro body and each invocation supplies the class
  name.

Running the module (`python scripts/gen_python_stubs.py`) rewrites the stub.
`--check` instead exits non-zero if the committed file is not what the source
implies, which is what `test_stub_completeness.py` uses.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "bindings" / "python" / "src" / "lib.rs"
STUB = ROOT / "bindings" / "python" / "python" / "wickra" / "__init__.pyi"

HEADER = '''"""Type stubs for the Wickra public API.

Generated by `scripts/gen_python_stubs.py` from `bindings/python/src/lib.rs`.
Do not edit by hand: run the script instead.
"""

from __future__ import annotations

import array
from typing import @TYPING@

__version__: str

# A candle accepted by `update`: either a
# `(open, high, low, close, volume, timestamp)` tuple or a mapping carrying
# those keys.
CandleLike = Union[
    Tuple[float, float, float, float, float, int],
    Mapping[str, Any],
]

# A batch input. Anything PyO3 can read as a sequence of numbers works, which
# includes `array.array("d")`, a `memoryview`, a plain list, and a NumPy array
# (structurally a sequence, though not a nominal `Sequence` to a type checker).
Series = Union[Sequence[float], memoryview]

# The same, for the millisecond timestamps the seasonality indicators take.
TimestampSeries = Union[Sequence[int], memoryview]
'''


TYPING_NAMES = ("Any", "List", "Mapping", "Optional", "Sequence", "Tuple", "Union")


def strip_lifetimes(ty: str) -> str:
    """Remove lifetimes and reference markers from a Rust type."""
    ty = re.sub(r"&(?:mut\s+)?", "", ty)
    # A lifetime is either a whole generic argument (`Bound<'py, PyAny>`) or a
    # qualifier on one (`'static str`); drop it and any comma it leaves behind.
    ty = re.sub(r"'[a-z_]+\s*,\s*", "", ty)
    ty = re.sub(r"'[a-z_]+\s*", "", ty)
    ty = re.sub(r"<\s*>", "", ty)
    ty = re.sub(r"\s+", " ", ty)
    return ty.strip()


def split_top_level(text: str, sep: str = ",") -> list[str]:
    """Split on `sep` at bracket depth zero."""
    out: list[str] = []
    depth = 0
    current = ""
    for ch in text:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth -= 1
        if ch == sep and depth == 0:
            out.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        out.append(current.strip())
    return out


def unwrap(ty: str, outer: str) -> str | None:
    """Return the single generic argument of `outer<...>`, or None."""
    prefix = outer + "<"
    if ty.startswith(prefix) and ty.endswith(">"):
        return ty[len(prefix) : -1].strip()
    return None


# `Matrix.__getitem__` returns a scalar for `m[i, j]` and a row for `m[i]`; the
# Rust signature is `PyAny` either way, so the union is stated here.
RETURN_OVERRIDES = {
    ("Matrix", "__getitem__"): "Union[float, array.array[float]]",
}

# Likewise for the key: `PyAny` covers a row index and a `(row, column)` pair.
ARG_OVERRIDES = {
    ("Matrix", "__getitem__", "key"): "Union[int, Tuple[int, int]]",
}

SCALARS = {
    "f64": "float",
    "f32": "float",
    "usize": "int",
    "u8": "int",
    "u16": "int",
    "u32": "int",
    "u64": "int",
    "i32": "int",
    "i64": "int",
    "isize": "int",
    "bool": "bool",
    "str": "str",
    "String": "str",
    "()": "None",
}


class Resolver:
    """Map Rust types onto the Python types the extension actually produces."""

    def __init__(self, aliases: dict[str, str]) -> None:
        self.aliases = aliases

    def resolve(
        self,
        ty: str,
        *,
        is_arg: bool,
        arg_name: str = "",
        matrix: bool = False,
        owner: str = "",
    ) -> str:
        ty = strip_lifetimes(ty)
        if ty in self.aliases:
            ty = strip_lifetimes(self.aliases[ty])
        if ty in SCALARS:
            return SCALARS[ty]
        if ty == "Self":
            # An alternate constructor such as `KST.classic()`. The `__init__`
            # case never reaches here; the caller renders it as `None`.
            return owner or "None"
        if ty in ("Buf1",):
            return "Series"
        if ty in ("BufI64",):
            return "TimestampSeries"
        if ty in ("Bound<PyAny>", "PyObject", "Py<PyAny>"):
            # Every `PyAny` the binding hands back is built by `f64_array` or by
            # `matrix`; every `PyAny` it takes in is a candle.
            if is_arg:
                return "CandleLike" if arg_name == "candle" else "Any"
            return "Matrix" if matrix else "array.array[float]"
        inner = unwrap(ty, "PyResult")
        if inner is not None:
            return self.resolve(inner, is_arg=is_arg, arg_name=arg_name, matrix=matrix, owner=owner)
        inner = unwrap(ty, "Option")
        if inner is not None:
            inner_ty = self.resolve(
                inner, is_arg=is_arg, arg_name=arg_name, matrix=matrix, owner=owner
            )
            return f"Optional[{inner_ty}]"
        inner = unwrap(ty, "Vec")
        if inner is not None:
            mapped = self.resolve(inner, is_arg=is_arg, arg_name=arg_name, matrix=matrix, owner=owner)
            return f"Sequence[{mapped}]" if is_arg else f"List[{mapped}]"
        if ty.startswith("(") and ty.endswith(")"):
            parts = split_top_level(ty[1:-1])
            mapped = [
                self.resolve(p, is_arg=is_arg, arg_name=arg_name, matrix=matrix, owner=owner)
                for p in parts
            ]
            return "Tuple[" + ", ".join(mapped) + "]"
        raise SystemExit(f"gen_python_stubs: no Python type for Rust type {ty!r}")


def balanced(text: str, open_index: int) -> str:
    """Return the `{...}` block starting at `open_index`."""
    depth = 0
    for i in range(open_index, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[open_index : i + 1]
    raise SystemExit("gen_python_stubs: unbalanced braces")


FN_RE = re.compile(
    r"fn\s+(?P<name>\w+)\s*(?:<[^>]*>)?\s*\((?P<args>.*?)\)\s*(?:->\s*(?P<ret>.+?))?\s*\{",
    re.S,
)


class Method:
    def __init__(self, name: str, args: list[tuple[str, str]], ret: str, kind: str) -> None:
        self.name = name
        self.args = args
        self.ret = ret
        self.kind = kind  # "new", "getter", "static", or "method"


def parse_impl(block: str) -> list[Method]:
    """Parse the top-level `fn` items of a `#[pymethods] impl` block."""
    methods: list[Method] = []
    depth = 0
    i = 0
    item_start = 0
    body = block
    while i < len(body):
        ch = body[i]
        if ch == "{":
            depth += 1
            if depth == 2:
                # A top-level item body: everything since the last item boundary
                # is its signature and attributes.
                head = body[item_start:i]
                fn_match = FN_RE.search(head + "{")
                if fn_match is not None:
                    methods.append(build_method(head, fn_match, body, i))
                nested = balanced(body, i)
                i += len(nested)
                depth -= 1
                item_start = i
                continue
        elif ch == "}":
            depth -= 1
        i += 1
    return methods


def build_method(head: str, fn_match: re.Match[str], body: str, brace_index: int) -> Method:
    attrs = head[: fn_match.start()]
    if "#[new]" in attrs:
        kind = "new"
    elif "#[getter]" in attrs:
        kind = "getter"
    elif "#[staticmethod]" in attrs:
        kind = "static"
    else:
        kind = "method"

    defaults: dict[str, str] = {}
    sig = re.search(r"#\[pyo3\(signature\s*=\s*\((?P<sig>.*?)\)\)\]", attrs, re.S)
    if sig is not None:
        for part in split_top_level(sig.group("sig")):
            if "=" in part:
                key, value = part.split("=", 1)
                defaults[key.strip()] = value.strip()

    args: list[tuple[str, str]] = []
    for part in split_top_level(fn_match.group("args") or ""):
        if part in ("&self", "&mut self", "self"):
            continue
        if ":" not in part:
            raise SystemExit(f"gen_python_stubs: cannot read parameter {part!r}")
        name, ty = part.split(":", 1)
        name = name.strip()
        ty = ty.strip()
        if strip_lifetimes(ty).startswith("Python"):
            continue
        args.append((name, ty))

    ret = (fn_match.group("ret") or "()").strip()
    method = Method(fn_match.group("name"), args, ret, kind)
    method.defaults = defaults  # type: ignore[attr-defined]
    method.returns_matrix = "matrix(" in balanced(body, brace_index)  # type: ignore[attr-defined]
    return method


def parse_source(text: str) -> tuple[dict[str, list[Method]], dict[str, str]]:
    """Return {python class name: methods} and the `type X = ...` aliases."""
    aliases: dict[str, str] = {}
    for match in re.finditer(r"^type\s+(\w+)(?:<[^>]*>)?\s*=\s*(.+?);", text, re.M | re.S):
        aliases[match.group(1)] = match.group(2)

    # Method sets defined once inside a `macro_rules!` wrapper.
    macro_methods: dict[str, list[Method]] = {}
    for match in re.finditer(r"macro_rules!\s+(\w+)\s*\{", text):
        name = match.group(1)
        macro_body = balanced(text, match.end() - 1)
        impl = re.search(r"#\[pymethods\]\s*impl\s+\$\w+\s*\{", macro_body)
        if impl is None:
            continue
        macro_methods[name] = parse_impl(balanced(macro_body, impl.end() - 1))

    classes: dict[str, list[Method]] = {}

    # Classes spelled out directly.
    for match in re.finditer(r"#\[pyclass\((?P<attrs>[^)]*)\)\]", text):
        name_attr = re.search(r'name\s*=\s*"([^"]+)"', match.group("attrs"))
        if name_attr is None:
            continue
        tail = text[match.end() : match.end() + 400]
        struct = re.search(r"\bstruct\s+(\w+)", tail)
        if struct is None:
            continue
        impl = re.search(
            r"#\[pymethods\]\s*impl\s+" + re.escape(struct.group(1)) + r"\s*\{", text
        )
        if impl is None:
            raise SystemExit(f"gen_python_stubs: no pymethods for {struct.group(1)}")
        classes[name_attr.group(1)] = parse_impl(balanced(text, impl.end() - 1))

    # Classes produced by a macro invocation. Each call carries exactly one
    # string literal, and that literal is the Python class name.
    for macro, methods in macro_methods.items():
        for call in re.finditer(re.escape(macro) + r"!\s*\((?P<args>.*?)\);", text, re.S):
            literals = re.findall(r'"([^"]+)"', call.group("args"))
            if len(literals) != 1:
                raise SystemExit(
                    f"gen_python_stubs: {macro}! call carries {len(literals)} string literals"
                )
            classes[literals[0]] = methods

    return classes, aliases


def parse_functions(text: str) -> list[Method]:
    """Module-level `#[pyfunction]` items."""
    functions: list[Method] = []
    for match in re.finditer(r"#\[pyfunction\]", text):
        fn_match = FN_RE.search(text, match.start())
        if fn_match is None:
            continue
        brace = fn_match.end() - 1
        # `build_method` reads the attributes out of the text preceding the
        # signature, so hand it one slice and re-match inside it.
        segment = text[match.start() : brace]
        local = FN_RE.search(segment + "{")
        if local is None:
            raise SystemExit("gen_python_stubs: cannot re-read a pyfunction signature")
        functions.append(build_method(segment, local, text, brace))
    return functions


def render_signature(
    method: Method, resolver: Resolver, *, is_free: bool, owner: str = ""
) -> str:
    parts = [] if is_free else ["self"]
    defaults = getattr(method, "defaults", {})
    for name, ty in method.args:
        annotated = ARG_OVERRIDES.get(
            (owner, method.name, name)
        ) or resolver.resolve(ty, is_arg=True, arg_name=name, owner=owner)
        if name in defaults:
            parts.append(f"{name}: {annotated} = {defaults[name]}")
        else:
            parts.append(f"{name}: {annotated}")
    if method.kind == "new":
        ret = "None"
    elif (owner, method.name) in RETURN_OVERRIDES:
        ret = RETURN_OVERRIDES[(owner, method.name)]
    else:
        ret = resolver.resolve(
            method.ret,
            is_arg=False,
            matrix=getattr(method, "returns_matrix", False),
            owner=owner,
        )
    name = "__init__" if method.kind == "new" else method.name
    return f"def {name}({', '.join(parts)}) -> {ret}: ..."


def render(classes: dict[str, list[Method]], functions: list[Method], resolver: Resolver) -> str:
    out: list[str] = []
    for name in sorted(classes):
        out.append("")
        out.append(f"class {name}:")
        lines: list[str] = []
        for method in classes[name]:
            rendered = render_signature(
                method, resolver, is_free=method.kind == "static", owner=name
            )
            if method.kind == "getter":
                lines.append("    @property")
            elif method.kind == "static":
                lines.append("    @staticmethod")
            lines.append("    " + rendered)
        out.extend(lines if lines else ["    ..."])
    for function in functions:
        out.append("")
        out.append(render_signature(function, resolver, is_free=True))
    body = "\n".join(out)
    # Import exactly the typing names the rendered body uses, so the stub never
    # carries an unused import once a shape stops appearing in the binding.
    used = sorted(name for name in TYPING_NAMES if re.search(rf"\b{name}\b", body))
    return HEADER.replace("@TYPING@", ", ".join(used)).rstrip("\n") + "\n" + body + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args()

    text = SRC.read_text(encoding="utf-8")
    classes, aliases = parse_source(text)
    resolver = Resolver(aliases)
    rendered = render(classes, parse_functions(text), resolver)

    if args.check:
        current = STUB.read_text(encoding="utf-8")
        if current != rendered:
            print(f"{STUB} is out of date; run python scripts/gen_python_stubs.py", file=sys.stderr)
            return 1
        print(f"{STUB} is up to date ({len(classes)} classes)")
        return 0

    STUB.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {STUB} ({len(classes)} classes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
